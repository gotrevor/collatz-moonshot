#!/usr/bin/env -S uv run --quiet --with pytest python3
"""Find sibling floor-parity conflicts in an exported delay-game witness.

arc_carry_compatibility.py scan WITNESS.json
arc_carry_compatibility.py lean WITNESS.json  (prints the Lean data snapshot)
arc_carry_compatibility.py test

Intervals reported are OPEN: their interior has constant available floor parities.
This diagnoses a given witness and faithful two-child translation, not every strategy.
Lean counterpart: ArcCarryCompatibility.sibling_floors_must_agree.
"""
from fractions import Fraction as F
import json
import hashlib
from pathlib import Path
import sys


def pieces_from_witness(witness):
    return [(row['word'], p['J'], F(p['covers'][0]), F(p['covers'][1]))
            for row in witness['rows'] for p in row['pieces']]


def forced_parity_zones(k, pieces):
    """Partition covered starts exactly; retain siblings with disjoint nonempty parity sets."""
    h = 1 << (k - 1)
    result = []
    for w in range(h):
        left = [p for p in pieces if p[0] == w]
        right = [p for p in pieces if p[0] == w + h]
        cuts = sorted({x for _, _, lo, hi in left + right for x in (lo, hi)})
        for lo, hi in zip(cuts, cuts[1:]):
            a = (lo + hi) / 2
            js = [{j for _, j, x, y in group if x < a < y} for group in (left, right)]
            ps = [{j % 2 for j in group} for group in js]
            if ps[0] and ps[1] and ps[0].isdisjoint(ps[1]):
                result.append(dict(words=[w, w + h], interval=[str(lo), str(hi)],
                                   sample=str(a), floors=[sorted(j) for j in js]))
    return result


def main(argv):
    if argv and argv[0] == 'test':
        import pytest
        return pytest.main([str(Path(__file__).with_name('test_arc_carry_compatibility.py')), *argv[1:]])
    if len(argv) == 2 and argv[0] == 'lean':
        source = Path(argv[1])
        data = source.read_bytes()
        witness = json.loads(data)
        intervals = {tuple(F(x) for x in row['interval']) for row in witness['rows'] if row['word'] == 0}
        if (witness['k'], F(witness['s']), F(witness['t']), F(witness['l'])) != (6, F(1, 10), F(4, 5), F(31, 100)):
            raise ValueError('Lean snapshot targets the beta=1/10, width=31/100, k=6 witness')
        if not {(F(0), F(473, 1024)), (F(2299, 4096), F(2839, 4096))} <= intervals:
            raise ValueError('Expected word-zero intervals are absent from this witness')
        print('/-\nCopyright (c) 2026 Trevor Morris. All rights reserved.\n'
              'Released under Apache 2.0 license as described in the file LICENSE.\n'
              'Authors: Trevor Morris\n-/')
        print('import CollatzMoonshot.Benchmark.ArcCarryCompatibility\n')
        print('namespace CollatzMoonshot.Benchmark.ArcCarryCompatibility\n')
        print('/-- Generated by experiments/arc_carry_compatibility.py lean from')
        print(f'{source.name}; SHA256 {hashlib.sha256(data).hexdigest()}.')
        print('This records floor covers, not a proof that the exported delay strategy wins. -/')
        print('def delayWitnessFloorPieces : List FloorPiece := [')
        pieces = pieces_from_witness(witness)
        for i, (w, j, lo, hi) in enumerate(pieces):
            print(f'  ⟨{w}, {j}, {lo}, {hi}⟩' + (',' if i + 1 < len(pieces) else ']'))
        print('\n/-- The immediate sibling-floor obstruction does not fire on the exported')
        print('beta=1/10, width=31/100, k=6 witness, on any open endpoint-partition cell. -/')
        print('theorem delay_witness_no_sibling_floor_conflicts :')
        print('    witnessHasSiblingConflict 6 delayWitnessFloorPieces = false := by native_decide')
        print('\n/-- Two intervals of word zero in the exported witness.  The third is unnecessary. -/')
        print('def witnessWordZeroCore : Set ℝ :=')
        print('  Set.Icc 0 (473 / 1024) ∪ Set.Icc (2299 / 4096) (2839 / 4096)')
        print('\n/-- No fixed residue and child-base assignment works for the whole word-zero set.')
        print('This excludes word-only relabelings; position-dependent encodings remain open. -/')
        print('theorem witness_word_zero_no_fixed_base (h A B : ℕ) (hh : 2 ≤ h) :')
        print('    ¬ FixedChildBaseRealization h A B witnessWordZeroCore := by')
        print('  apply two_starts_preclude_fixed_child_base h A B hh')
        print('  · norm_num [witnessWordZeroCore, Set.mem_union, Set.mem_Icc]')
        print('  · norm_num [witnessWordZeroCore, Set.mem_union, Set.mem_Icc]')
        print('\nend CollatzMoonshot.Benchmark.ArcCarryCompatibility')
        return 0
    if len(argv) == 2 and argv[0] == 'scan':
        witness = json.loads(Path(argv[1]).read_text())
        zones = forced_parity_zones(witness['k'], pieces_from_witness(witness))
        print(json.dumps(dict(zones=len(zones), pairs=len({tuple(z['words']) for z in zones}),
                              examples=zones[:20]), indent=2))
        return 0
    print(__doc__)
    return 2


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
